/// Icon size scale. Use Material "rounded" (or "outlined") icons throughout.
///
/// sm – inline with caption/meta text and inside badges
/// md – default: buttons, list tiles, form field prefixes
/// lg – app bar actions and bottom navigation
/// xl – empty / error state illustrations
class AppIconSize {
  static const double sm = 16;
  static const double md = 20;
  static const double lg = 24;
  static const double xl = 32;
}
