/// Icon size scale. Use Material "rounded" (or "outlined") icons throughout.
///
/// xxs – inside dense status badges
/// xs  – inside status badges and metadata tags
/// sm  – inline with caption/meta text, filter-chip check
/// md  – default: buttons, list tiles, form field prefixes, bottom bar
/// lg  – app bar actions and navigation rail
/// xl  – empty / error / success state illustrations
class AppIconSize {
  static const double xxs = 12;
  static const double xs = 14;
  static const double sm = 16;
  static const double md = 20;
  static const double lg = 24;
  static const double xl = 32;
}
